"""
MarineMine Pro — Report Generation Module
==========================================
Produces executive summary markdown and CSV reports containing complete
dataset information, preprocessing history, EDA insights, ML metrics,
and environmental disclaimers.
"""

from __future__ import annotations

import datetime
import io
import logging
from typing import Any, Dict, List, Optional
import pandas as pd

logger = logging.getLogger(__name__)


def get_report_disclaimer() -> str:
    return (
        "> [!IMPORTANT]\n"
        "> **ACADEMIC & DEMONSTRATION DISCLAIMER**\n"
        "> This report was generated by **MarineMine Pro — Mining Patterns of Marine Pollution**.\n"
        "> Observations and predictions are computational estimates for scientific and academic exploration.\n"
        "> Synthetic demonstration records must not be interpreted as certified government environmental sensor data."
    )


def generate_text_report(
    dataset_info: Dict[str, Any],
    preprocessing_report: Optional[Dict[str, Any]] = None,
    eda_summary: Optional[Dict[str, Any]] = None,
    clustering_results: Optional[Dict[str, Any]] = None,
    classification_results: Optional[Dict[str, Any]] = None,
    prediction_results: Optional[Dict[str, Any]] = None,
    association_rules_summary: Optional[Dict[str, Any]] = None,
    hotspot_summary: Optional[Dict[str, Any]] = None,
) -> str:
    """
    Generate a full markdown analysis report.
    """
    now_str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    lines = [
        "# 🌊 MarineMine Pro: Comprehensive Marine Pollution Analysis Report",
        f"**Generated On:** {now_str}  ",
        "**System:** MarineMine Pro (Data Mining & Machine Learning Suite)  ",
        "",
        "---",
        "",
        get_report_disclaimer(),
        "",
        "## 1. Executive Summary & Dataset Profile",
        f"- **Dataset Name:** `{dataset_info.get('dataset_name', 'Marine Pollution Dataset')}`",
        f"- **Total Records:** {dataset_info.get('total_rows', 'N/A')}",
        f"- **Total Features (Columns):** {dataset_info.get('total_columns', 'N/A')}",
        f"- **Memory Footprint:** {dataset_info.get('memory_usage_mb', 'N/A')} MB",
        f"- **Identified Date Range:** {dataset_info.get('date_range', 'Not Specified')}",
        f"- **Missing Value Frequency:** {dataset_info.get('missing_pct', 0.0)}%",
        "",
    ]

    # Preprocessing Section
    lines.append("## 2. Data Preprocessing & Cleaning History")
    if preprocessing_report:
        lines.extend([
            f"- **Original Rows:** {preprocessing_report.get('original_rows', 'N/A')}",
            f"- **Processed Clean Rows:** {preprocessing_report.get('final_rows', 'N/A')}",
            f"- **Duplicate Rows Removed:** {preprocessing_report.get('duplicates_removed', 0)}",
            f"- **Missing Value Imputation Strategy:** `{preprocessing_report.get('missing_strategy', 'Applied')}`",
            f"- **Transformations Applied:** {', '.join(preprocessing_report.get('transformations', ['Standard Cleaning']))}",
            "",
        ])
    else:
        lines.append("- *No dedicated preprocessing transformations logged (raw dataset utilized).*")
        lines.append("")

    # EDA Section
    lines.append("## 3. Exploratory Data Analysis (EDA) Highlights")
    if eda_summary:
        pol_stats = eda_summary.get("pollution_stats", {})
        if pol_stats:
            lines.extend([
                "### Pollution Concentration Statistics",
                f"- **Mean Concentration:** {pol_stats.get('mean', 'N/A')}",
                f"- **Median Concentration:** {pol_stats.get('median', 'N/A')}",
                f"- **Maximum Peak Level:** {pol_stats.get('max', 'N/A')}",
                f"- **Minimum Detected Level:** {pol_stats.get('min', 'N/A')}",
                "",
            ])

        top_types = eda_summary.get("top_pollution_types", {})
        if top_types:
            lines.append("### Predominant Pollution Categories")
            for ptype, cnt in top_types.items():
                lines.append(f"- **{ptype}:** {cnt} recorded occurrences")
            lines.append("")

        top_reg = eda_summary.get("top_polluted_regions", [])
        if top_reg:
            lines.append("### Highest Average Pollution Regions")
            for reg in top_reg:
                lines.append(f"- **{reg.get('region', reg.get('detected_region', 'Region'))}:** Mean = {reg.get('mean_pollution', 'N/A')}")
            lines.append("")
    else:
        lines.append("- *General exploratory analytics indicate multimodal pollution distribution across geographical zones.*")
        lines.append("")

    # Clustering Section
    lines.append("## 4. Unsupervised Pattern Discovery (K-Means Clustering)")
    if clustering_results and "n_clusters" in clustering_results:
        lines.extend([
            f"- **Optimal Clusters (k):** {clustering_results.get('n_clusters')}",
            f"- **Silhouette Coefficient:** {clustering_results.get('silhouette_score', 'N/A')}",
            f"- **Features Included in Vector Space:** {', '.join(clustering_results.get('features', []))}",
            "",
        ])
        if "descriptions" in clustering_results:
            lines.append("### Cluster Profiles:")
            for cid, desc in clustering_results["descriptions"].items():
                lines.append(f"- **{cid}:** {desc}")
            lines.append("")
    else:
        lines.append("- *K-Means clustering has not been executed for this session yet.*")
        lines.append("")

    # Classification Section
    lines.append("## 5. Supervised Categorization (Classification)")
    if classification_results and "comparison" in classification_results:
        lines.extend([
            f"- **Target Attribute:** `{classification_results.get('target_col', 'N/A')}`",
            f"- **Tested Algorithms:** Decision Tree, Random Forest, Logistic Regression",
            "",
            "### Performance Evaluation Matrix:",
        ])
        comp_df = classification_results["comparison"]
        if isinstance(comp_df, pd.DataFrame):
            lines.append(comp_df.to_markdown(index=False) if hasattr(comp_df, "to_markdown") else str(comp_df))
        lines.append("")
    else:
        lines.append("- *Classification models pending execution or target attribute unselected.*")
        lines.append("")

    # Association Rules Section
    lines.append("## 6. Association Rule Mining (Apriori)")
    if association_rules_summary and "rules_count" in association_rules_summary:
        lines.extend([
            f"- **Frequent Itemsets Discovered:** {association_rules_summary.get('itemsets_count', 0)}",
            f"- **Valid Association Rules:** {association_rules_summary.get('rules_count', 0)}",
            f"- **Parameters:** Min Support = {association_rules_summary.get('min_support', 'N/A')}, Min Confidence = {association_rules_summary.get('min_confidence', 'N/A')}",
            "",
        ])
        if "top_rules_text" in association_rules_summary:
            lines.append("### Salient Discovered Rules:")
            for r in association_rules_summary["top_rules_text"]:
                lines.append(f"- {r}")
            lines.append("")
    else:
        lines.append("- *Association rule mining pending execution.*")
        lines.append("")

    # Prediction Section
    lines.append("## 7. Numerical Estimation & Trend Modeling (Regression)")
    if prediction_results and "comparison" in prediction_results:
        lines.extend([
            f"- **Predicted Target:** `{prediction_results.get('target_col', 'N/A')}`",
            f"- **Models Trained:** Linear Regression & Random Forest Regressor",
            "",
            "### Regression Metrics Comparison:",
        ])
        comp_df = prediction_results["comparison"]
        if isinstance(comp_df, pd.DataFrame):
            lines.append(comp_df.to_markdown(index=False) if hasattr(comp_df, "to_markdown") else str(comp_df))
        lines.append("")
    else:
        lines.append("- *Regression modeling pending execution.*")
        lines.append("")

    # Hotspot Section
    lines.append("## 8. Geographical Hotspot Identification")
    if hotspot_summary and "hotspots_count" in hotspot_summary:
        lines.extend([
            f"- **Validated Geographical Observations:** {hotspot_summary.get('valid_geo_records', 'N/A')}",
            f"- **High-Severity Hotspot Clusters:** {hotspot_summary.get('hotspots_count', 'N/A')}",
            "",
        ])
    else:
        lines.append("- *Spatial hotspot analysis pending or coordinates unavailable.*")
        lines.append("")

    # Limitations & Roadmap
    lines.extend([
        "## 9. Environmental Analytics Limitations & Academic Validity",
        "1. **Synthetic & Sensor Variance:** Real-world maritime telemetry involves drift, oceanic currents, and seasonal thermoclines.",
        "2. **Station Density:** Point observations represent sparse sampling; spatial interpolation requires high-density maritime buoy arrays.",
        "3. **Algorithmic Scope:** Machine learning models approximate empirical relationships and must be paired with biogeochemical ocean models (e.g., ROMS or Copernicus Marine Service).",
        "",
        "---",
        "**MarineMine Pro © 2026 — Advanced Environmental Data Intelligence**",
    ])

    return "\n".join(lines)


def generate_csv_exports(results_dict: Dict[str, Any]) -> Dict[str, str]:
    """
    Format various DataFrames into CSV strings for browser downloads.
    """
    exports = {}
    for name, obj in results_dict.items():
        if isinstance(obj, pd.DataFrame) and not obj.empty:
            exports[f"{name}.csv"] = obj.to_csv(index=False)
    return exports


def try_generate_pdf(markdown_text: str) -> Optional[bytes]:
    """
    Generate a simple PDF document from text if reportlab is available.
    """
    try:
        from reportlab.lib.pagesizes import letter
        from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
        from reportlab.lib import colors

        buffer = io.BytesIO()
        doc = SimpleDocTemplate(buffer, pagesize=letter, rightMargin=54, leftMargin=54, topMargin=54, bottomMargin=54)
        styles = getSampleStyleSheet()

        title_style = ParagraphStyle(
            'ReportTitle',
            parent=styles['Heading1'],
            textColor=colors.HexColor('#0A3D62'),
            fontSize=18,
            leading=22,
            spaceAfter=12
        )
        h2_style = ParagraphStyle(
            'ReportH2',
            parent=styles['Heading2'],
            textColor=colors.HexColor('#1E90FF'),
            fontSize=13,
            leading=16,
            spaceBefore=10,
            spaceAfter=6
        )
        body_style = ParagraphStyle(
            'ReportBody',
            parent=styles['Normal'],
            fontSize=10,
            leading=14,
            spaceAfter=4
        )

        story = []
        for line in markdown_text.split("\n"):
            line = line.strip()
            if not line:
                story.append(Spacer(1, 4))
                continue
            if line.startswith("# "):
                story.append(Paragraph(line[2:].replace("<", "&lt;").replace(">", "&gt;"), title_style))
            elif line.startswith("## "):
                story.append(Paragraph(line[3:].replace("<", "&lt;").replace(">", "&gt;"), h2_style))
            elif line.startswith("### "):
                story.append(Paragraph(f"<b>{line[4:]}</b>".replace("<", "&lt;").replace(">", "&gt;"), body_style))
            elif line.startswith("- "):
                clean = line[2:].replace("**", "<b>").replace("<", "&lt;").replace(">", "&gt;")
                story.append(Paragraph(f"• {clean}", body_style))
            elif not line.startswith("---") and not line.startswith(">"):
                clean = line.replace("**", "<b>").replace("<", "&lt;").replace(">", "&gt;")
                story.append(Paragraph(clean, body_style))

        doc.build(story)
        buffer.seek(0)
        return buffer.getvalue()
    except Exception as e:
        logger.warning(f"PDF generation failed: {e}")
        return None
